"""AI / ML endpoints.

* ``GET  /api/ai/status``   - what the platform can honestly claim (model, gaps).
* ``GET  /api/ai/models``   - trained model versions and their evaluation metrics.
* ``POST /api/ai/train``    - train and (optionally) activate a new version.
* ``POST /api/ai/predict``  - classify one risk entry, always beside the rule-based class.
* ``GET  /api/ai/insights`` - deterministic, reproducible portfolio insights.

Training on ``dataset="stored"`` uses only the caller's own organization, so one
tenant's register never becomes another tenant's training data.
"""

from __future__ import annotations

import logging
from datetime import date
from typing import Annotated, Optional

from fastapi import APIRouter, HTTPException, Query, Request, status
from sqlalchemy import func, select

from .. import domain
from ..audit import record_audit
from ..config import settings
from ..deps import CanManage, CanWrite, SessionDep, Tenant, client_ip
from ..ml import ml_stack_available, optional_runtime
from ..ml.features import FEATURE_SCHEMA, TARGET_DESCRIPTION, TARGET_LABEL
from ..ml.inference import active_model, predict_risk
from ..ml.train import MODEL_LIMITATIONS, persist_artifact, record_model_version, stored_dataset, synthetic_dataset, train
from ..models import ModelVersion, Risk
from ..schemas import (
    Insight,
    ModelStatusOut,
    ModelVersionOut,
    PredictRequest,
    PredictionOut,
    TrainingOut,
    TrainingRequest,
)
from ..services.insights import build_insights

logger = logging.getLogger("finrisk.ai")

router = APIRouter(prefix="/api/ai", tags=["ai"])

#: Row count used when training on synthetic data without an explicit request.
DEFAULT_SYNTHETIC_ROWS = 320
MAX_SYNTHETIC_ROWS = 5000


@router.get("/status", response_model=ModelStatusOut)
def model_status(db: SessionDep, tenant: Tenant) -> ModelStatusOut:
    """Report the active model and the platform's honest capability state."""
    available, detail = ml_stack_available()
    model_row = active_model(db)
    stored_rows = int(
        db.execute(
            select(func.count(Risk.id)).where(Risk.organization_id == tenant.organization_id)
        ).scalar_one()
    )

    caveats: list[str] = []
    if not available:
        caveats.append(detail)
    if model_row is None:
        caveats.append(
            "No model has been trained yet, so predictions fall back to the documented rule-based "
            "5x5 matrix."
        )
    if stored_rows < settings.retrain_min_rows:
        caveats.append(
            f"Your organization has {stored_rows} risk register entr"
            f"{'y' if stored_rows == 1 else 'ies'}; at least {settings.retrain_min_rows} are required "
            "to train on stored data. The synthetic dataset is available for demonstration."
        )
    caveats.append(
        "Nothing on the AI Insights page is generated by a language model: every figure there is a "
        "deterministic calculation from persisted rows, and a human reviewer owns each conclusion."
    )

    return ModelStatusOut(
        available=available and model_row is not None,
        detail=" ".join(caveats) if caveats else "An active model is available.",
        active_model=ModelVersionOut.model_validate(model_row) if model_row else None,
        optional_runtime=optional_runtime(),
        feature_schema=FEATURE_SCHEMA,
        target_label=TARGET_LABEL,
        target_description=TARGET_DESCRIPTION,
        limitations=MODEL_LIMITATIONS,
        minimum_training_rows=settings.retrain_min_rows,
        stored_rows_available=stored_rows,
    )


@router.get("/models", response_model=list[ModelVersionOut])
def list_models(
    db: SessionDep,
    tenant: Tenant,
    limit: Annotated[int, Query(ge=1, le=100)] = 20,
) -> list[ModelVersionOut]:
    """Every trained model version, newest first, with its evaluation metrics."""
    rows = db.execute(
        select(ModelVersion)
        .order_by(ModelVersion.trained_at.desc(), ModelVersion.id.desc())
        .limit(limit)
    ).scalars().all()
    return [ModelVersionOut.model_validate(row) for row in rows]


@router.post("/train", response_model=TrainingOut, status_code=status.HTTP_201_CREATED)
def train_model(
    payload: TrainingRequest,
    request: Request,
    db: SessionDep,
    tenant: CanManage,
) -> TrainingOut:
    """Train a new model version and optionally make it the active one."""
    available, detail = ml_stack_available()
    if not available:
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=detail)

    if payload.dataset == "stored":
        rows = stored_dataset(db, organization_id=tenant.organization_id)
        if not rows:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=(
                    "There are no risk register entries in your organization to train on. "
                    "Add risks, or train on the synthetic demonstration dataset."
                ),
            )
    else:
        count = payload.synthetic_rows or DEFAULT_SYNTHETIC_ROWS
        rows = synthetic_dataset(min(max(count, 40), MAX_SYNTHETIC_ROWS))

    try:
        result = train(dataset=payload.dataset, rows=rows)
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc
    except RuntimeError as exc:  # pragma: no cover - depends on the optional runtime
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=str(exc)) from exc

    try:
        artifact_path = persist_artifact(result)
    except Exception as exc:  # noqa: BLE001 - report the real reason, never a bare 500
        logger.exception("Could not persist the trained model artifact.")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"The model was trained but its artifact could not be written: {exc}",
        ) from exc

    model_row = record_model_version(
        db, result, artifact_path=artifact_path, activate=payload.activate
    )

    record_audit(
        db,
        action=domain.AuditAction.MODEL_TRAINED.value,
        user=tenant.user,
        organization_id=tenant.organization_id,
        entity_type="model_version",
        entity_id=model_row.id,
        detail={
            "version": result.version,
            "algorithm": result.algorithm,
            "dataset": result.dataset_kind,
            "rows": result.dataset_rows,
            "macro_f1": result.metrics.get("macro_f1"),
            "activated": payload.activate,
        },
        ip_address=client_ip(request),
    )
    db.commit()
    db.refresh(model_row)

    return TrainingOut(
        model=ModelVersionOut.model_validate(model_row),
        comparison=result.comparison,
        summary=result.summary,
    )


@router.post("/predict", response_model=PredictionOut)
def predict(
    payload: PredictRequest,
    request: Request,
    db: SessionDep,
    tenant: CanWrite,
) -> PredictionOut:
    """Classify a risk register entry, always beside the rule-based class."""
    risk = db.get(Risk, payload.risk_id)
    if risk is None or risk.organization_id != tenant.organization_id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Risk not found.")

    report = predict_risk(
        db,
        risk,
        organization_id=tenant.organization_id,
        requested_by=tenant.user,
        persist=payload.persist,
    )
    prediction = report.prediction

    record_audit(
        db,
        action=domain.AuditAction.PREDICTION_REQUESTED.value,
        user=tenant.user,
        organization_id=tenant.organization_id,
        entity_type="risk",
        entity_id=risk.id,
        detail={
            "predicted_class": prediction.predicted_class,
            "rule_based_class": prediction.rule_based_class,
            "used_fallback": prediction.used_fallback,
            "model_version": prediction.model_version,
            "persisted": payload.persist,
        },
        ip_address=client_ip(request),
    )
    db.commit()

    return prediction


@router.get("/insights", response_model=list[Insight])
def insights(
    db: SessionDep,
    tenant: Tenant,
    start_date: Annotated[Optional[date], Query()] = None,
    end_date: Annotated[Optional[date], Query()] = None,
) -> list[Insight]:
    """Deterministic portfolio insights, each traceable to persisted rows."""
    return build_insights(
        db,
        tenant.organization_id,
        currency=tenant.organization.currency,
        start_date=start_date,
        end_date=end_date,
    )
